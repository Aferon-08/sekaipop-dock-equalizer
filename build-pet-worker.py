#!/usr/bin/env python3
"""Bundle the authoritative pure QML JS libraries for Qt's isolated worker."""
from pathlib import Path
import re, hashlib, sys
root=Path(__file__).resolve().parent
parts=['// Generated by build-pet-worker.py. Edit the authoritative .js libraries.\n']
for name,alias in [('GlassRoutes.js','Routes'),('PetPhysics.js','Physics'),('PetNavigation.js','Nav'),('PetMotion.js','Motion'),('BubbleTransfer.js','Bubble')]:
    source=(root/name).read_text();exports=re.findall(r'^function\s+(\w+)\(',source,re.M)
    code=re.sub(r'^\.(pragma|import).*\n','',source,flags=re.M)
    parts.append('// '+name+' sha256='+hashlib.sha256(source.encode()).hexdigest()+'\nconst '+alias+'=(()=>{\n'+code+'\nreturn {'+','.join(exports)+'};\n})();\n')
parts.append('''WorkerScript.onMessage=function(message){
 let result;
 try {
  if(message.kind==="room"){
   let path=Nav.roomPath(message.room,message.start,message.end,message.walls)
   const blockers=Physics.blockers(message.room,message.walls)
   if(path)path=Nav.flowing(path,Math.min(message.room.w,message.room.h)*.16,message.seed,p=>Physics.clearance(message.room,p,blockers,true)>=.001)
   result={path:path,reason:path?null:"no safe inside path"}
  }else{
   result=Bubble.plan(message.source,message.target,message.rooms,message.walls,message.context,message.origin)
   if(!result.reason && message.requireReturn){
    const back=Bubble.plan(message.target,message.source,message.rooms,message.walls,message.context,result.entry)
    if(back.reason)result={reason:"no safe return: "+back.reason};else result.returnPlan=back
   }
  }
 }
 catch(error){result={reason:"planner error: "+String(error)+" | "+String(error.stack)}}
 WorkerScript.sendMessage({generation:message.generation,request:message.request,actor:message.actor,kind:message.kind,result:result});
};
''')
text=''.join(parts);target=root/'PetPlannerWorker.mjs'
if '--check' in sys.argv:
    if not target.exists() or target.read_text()!=text:raise SystemExit('Worker bundle stale; run build-pet-worker.py')
    print('PASS worker bundle matches authoritative libraries')
else:target.write_text(text)
